"use strict";
const assert=require('node:assert/strict');
const {build}=require('./static/disk_units.js');
const guard={class_path:'/Game/Mobs/BP_Guard.BP_Guard_C',display_name:'守门人',internal_name:'BP_Guard',browse_type:'BOSS',codex_entry_kind:'primary',map_name:'测试地图',spawnable:false};
const actor={class_path:'/Game/Seq/BP_Actor.BP_Actor_C',display_name:'演出角色',browse_type:'演出角色候选',inheritance_verified:true,resolved_unit_kind:'character'};
const unknown={class_path:'/Game/Mobs/BP_Guard_Physics.BP_Guard_Physics_C',display_name:'身份待核对',browse_type:'待分类'};
const paths=['/game/mobs/bp_guard','/Game/UI/T_BP_Guard','/Game/Seq/BP_Actor','/Game/Mobs/BP_Guard_Physics'];
const index={schema_version:1,verified:true,total_files:4,files:paths.map(path=>({virtual_package:path,file_path:path+'.uasset',container:'main.utoc'}))};
const catalog=[guard,actor,unknown];
const all=build(index,catalog);
assert.equal(all.matched,2);
assert.deepEqual(all.unit_summary,{verified:2,candidates:1,by_kind:{codex:1,character:1}});
assert.equal(build(index,catalog,{query:'守门人',type:'BOSS'}).matched,1);
assert.equal(build(index,catalog,{query:'测试地图'}).matched,1);
assert.equal(build(index,catalog,{query:'T_BP_Guard'}).matched,0,'a texture with a similar name is not a unit');
assert.equal(build(index,catalog,{kind:'unit_candidate'}).matched,1);
assert.equal(build(index,catalog,{offset:1,limit:1}).files.length,1);
assert.equal(build({...index,verified:false},catalog).available,false);
assert.equal(build(index,catalog.map(unit=>({...unit,codex_entry_kind:undefined,inheritance_verified:false}))).matched,0);
assert.ok(!('spawnable' in all.files[0].unit),'directory browsing must not assign spawn permission');
assert.equal(guard.spawnable,false,'original catalogue permissions remain unchanged');
console.log('disk_units: PASS (exact package, Chinese search, evidence, types, pagination, permissions)');
