const assert=require('node:assert/strict');
const keys=require('./static/unit_shortcuts.js');
assert.equal(keys.keyCode({code:'KeyQ'}),81);
assert.equal(keys.keyCode({code:'Digit3'}),51);
assert.equal(keys.keyCode({code:'Numpad3'}),99);
assert.equal(keys.keyCode({code:'F12'}),123);
assert.equal(keys.keyCode({code:'Unidentified'}),null);
assert.equal(keys.label(81,5),'Ctrl+Shift+Q');
assert.equal(keys.label(99,0),'Num3');
const owner={id:'unit-a',display_name:'斧老大：彭猛',unit_shortcut:{key_code:51,modifiers:1}};
assert(keys.conflict('unit-b',51,4,[owner]).includes('斧老大：彭猛'));
assert(keys.conflict('unit-b',51,4,[owner]).includes('Ctrl+3'),'show the actual occupying chord, even when modifiers differ');
assert.equal(keys.conflict('unit-a',51,0,[owner]),'','rebinding the same unit is permitted');
assert(keys.conflict('unit-b',116,0,[],{key_stop:'F5'}).includes('停止并清理'));
assert.equal(keys.conflict('unit-b',113,0),'','an unassigned former fixed key is available');
assert(keys.conflict('unit-b',113,0,[],{key_cycle_team:'VK_113_MOD_0'}).includes('切换召唤队伍'));
assert(keys.conflict('unit-b',117,0,[],{}, {toggle_camera:{key_code:117,modifiers:0}}).includes('自由观战'));
assert(keys.systemConflict(82,1).includes('UE4SS'));
assert.equal(keys.conflict('unit-b',0,0,[owner]),'','clearing never conflicts');
assert.equal(keys.conflict('unit-b',52,0,[owner]),'');
console.log('unit_shortcuts: PASS (physical keyboard codes, number pad distinction, modifier labels)');
